--
--   app_recipes          one row per recipe. Everyone reads the FREE published ones in full; Tropical+ recipes
--                        are read in full only by Tropical+ members (is_tropical_plus) and admins. Only admins write.
--   is_tropical_plus()   true for a signed-in person with an active subscription or at least one paid box
--                        (my_journey().paid_boxes, the same count as the Clube Tropical stamps).
--   app_recipe_cards()   every published recipe's card (name, emoji, color, photo, cravings, time, what it needs),
--                        without ingredients or steps: the app ranks with it and shows a locked recipe as a teaser.
--
-- Seeded with the 13 launch recipes from src/lib/vontade.ts (generated by tools/vontade-seed.mjs). ON CONFLICT DO
-- NOTHING, so running this again never overwrites Dolly's edits.
--
-- Safe to run more than once. Until it runs, the app uses its built-in recipes and the admin page shows a
-- "rode a migration 48" hint. Run it BEFORE or right after the deploy; nothing else depends on it.

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS public.app_recipes (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    slug          text UNIQUE NOT NULL CHECK (slug ~ '^[a-z0-9-]+$'),
    name          text NOT NULL,
    emoji         text NOT NULL DEFAULT '🍓',
    photo_url     text,
    -- One of the seven Sweet Escape colors (COLORS in lib/vontade.ts).
    color         text NOT NULL DEFAULT '#f7c600',
    -- chocolate | cremoso | fresquinho | crocante
    cravings      text[] NOT NULL DEFAULT '{}',
    minutes       integer NOT NULL DEFAULT 5 CHECK (minutes BETWEEN 1 AND 120),
    -- Fridge or freezer time on top of the hands-on minutes.
    wait_minutes  integer NOT NULL DEFAULT 0 CHECK (wait_minutes BETWEEN 0 AND 1440),
    -- Pantry keys (PANTRY in lib/vontade.ts) the recipe can't do without.
    needs         text[] NOT NULL DEFAULT '{}',
    ingredients   text[] NOT NULL DEFAULT '{}',
    steps         text[] NOT NULL DEFAULT '{}',
    tip           text,
    -- Allergen ids from lib/allergens.ts.
    contains      text[] NOT NULL DEFAULT '{}',
    is_free       boolean NOT NULL DEFAULT false,
    published     boolean NOT NULL DEFAULT false,
    sort          integer NOT NULL DEFAULT 100,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION public.app_recipes_touch()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS app_recipes_touch ON public.app_recipes;
CREATE TRIGGER app_recipes_touch BEFORE UPDATE ON public.app_recipes
    FOR EACH ROW EXECUTE FUNCTION public.app_recipes_touch();

-- ------------------------------------------------------------ Tropical+
CREATE OR REPLACE FUNCTION public.is_tropical_plus()
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    IF auth.uid() IS NULL THEN
        RETURN false;
    END IF;
    IF EXISTS (SELECT 1 FROM public.subscriptions WHERE user_id = auth.uid() AND status IS DISTINCT FROM 'cancelled') THEN
        RETURN true;
    END IF;
    RETURN COALESCE((public.my_journey() ->> 'paid_boxes')::int, 0) >= 1;
END;
$$;
REVOKE ALL ON FUNCTION public.is_tropical_plus() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_tropical_plus() TO anon, authenticated;

-- ------------------------------------------------------------ who reads what
ALTER TABLE public.app_recipes ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS app_recipes_read ON public.app_recipes;
CREATE POLICY app_recipes_read ON public.app_recipes
    FOR SELECT USING (
        (SELECT public.is_admin())
        OR (published AND (is_free OR (SELECT public.is_tropical_plus())))
    );
DROP POLICY IF EXISTS app_recipes_admin_write ON public.app_recipes;
CREATE POLICY app_recipes_admin_write ON public.app_recipes
    FOR ALL TO authenticated USING (public.is_admin()) WITH CHECK (public.is_admin());

GRANT SELECT ON public.app_recipes TO anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.app_recipes TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.app_recipes TO service_role;

-- The cards of every published recipe, locked ones included, with no ingredients or steps.
CREATE OR REPLACE FUNCTION public.app_recipe_cards()
RETURNS TABLE (
    slug text, name text, emoji text, photo_url text, color text, cravings text[],
    minutes integer, wait_minutes integer, needs text[], is_free boolean, sort integer
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT r.slug, r.name, r.emoji, r.photo_url, r.color, r.cravings, r.minutes, r.wait_minutes, r.needs, r.is_free, r.sort
    FROM public.app_recipes r
    WHERE r.published
    ORDER BY r.sort, r.name;
$$;
REVOKE ALL ON FUNCTION public.app_recipe_cards() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.app_recipe_cards() TO anon, authenticated;

